const { _electron: electron } = require('playwright')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')

;(async () => {
  const root = path.resolve(__dirname, '..')
  const artifacts = path.join(root, 'artifacts')
  fs.mkdirSync(artifacts, { recursive: true })
  const sandbox = fs.mkdtempSync(path.join(artifacts, 'updates-ui-'))
  const { version } = require('../package.json')
  const nextVersion = version.replace(/\d+$/, patch => String(Number(patch) + 1))
  const repository = 'https://github.com/kaka-looking/fleet-bridge-'
  const env = { ...process.env, FLEET_DATA_DIR: path.join(sandbox, 'app'), FLEET_CODEX_HOME: path.join(sandbox, 'codex') }
  delete env.ELECTRON_RUN_AS_NODE
  let application
  try {
    application = await electron.launch({ args: [root, '--force-device-scale-factor=1'], env })
    const page = await application.firstWindow()
    await page.getByRole('heading', { name: /你自己的模型舰队/ }).waitFor()
    await application.evaluate(({ shell }) => {
      globalThis.__fleetOpenedUrls = []
      shell.openExternal = async url => { globalThis.__fleetOpenedUrls.push(url) }
    })
    const sourceLink = page.locator('.sidebar-bottom').getByRole('link', { name: 'GitHub 开源仓库' })
    assert.equal(await sourceLink.getAttribute('href'), repository)
    await sourceLink.click()
    assert.deepEqual(await application.evaluate(() => globalThis.__fleetOpenedUrls), [repository])
    await page.locator('.app-version').getByText(`v${version}`, { exact: true }).waitFor()
    await page.evaluate(async () => { const state = await window.fleet.snapshot(); await window.fleet.setGateway(false); await window.fleet.saveSettings({ ...state.settings, autoStart: false, theme: 'light' }) })
    await page.getByRole('button', { name: '设置', exact: true }).click()
    const updates = page.getByLabel('应用更新', { exact: true })
    await updates.getByText('开发模式不执行自动安装更新。', { exact: true }).waitFor()
    assert.equal(await updates.getByRole('button', { name: '检查更新', exact: true }).isDisabled(), true)
    assert.equal(await page.getByRole('switch', { name: '自动更新', exact: true }).isChecked(), true)
    await page.getByRole('switch', { name: '自动检查更新', exact: true }).uncheck()
    await page.getByRole('switch', { name: '自动下载更新', exact: true }).uncheck()
    await page.getByRole('button', { name: '保存设置', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '设置已保存' }).waitFor()
    const settings = await page.evaluate(async () => (await window.fleet.snapshot()).settings)
    assert.equal(settings.autoCheckUpdates, false); assert.equal(settings.autoDownloadUpdates, false); assert.equal(settings.autoInstallUpdates, false)
    await page.getByRole('switch', { name: '自动更新', exact: true }).check()
    assert.equal(await page.getByRole('switch', { name: '自动检查更新', exact: true }).isChecked(), true)
    assert.equal(await page.getByRole('switch', { name: '自动下载更新', exact: true }).isChecked(), true)
    await page.getByRole('switch', { name: '自动下载更新', exact: true }).uncheck()
    assert.equal(await page.getByRole('switch', { name: '自动更新', exact: true }).isChecked(), false)
    await page.getByRole('switch', { name: '自动更新', exact: true }).check()
    await page.getByRole('button', { name: '保存设置', exact: true }).click()
    await page.waitForFunction(async () => (await window.fleet.snapshot()).settings.autoInstallUpdates === true)
    await updates.getByRole('link', { name: 'GitHub 开源仓库' }).click()
    assert.deepEqual(await application.evaluate(() => globalThis.__fleetOpenedUrls), [repository, repository])
    await application.evaluate(({ ipcMain, BrowserWindow }, { version, nextVersion, repository }) => {
      const state = { mode: 'installer', phase: 'idle', currentVersion: version, releasesUrl: `${repository}/releases/latest`, message: '测试更新源' }
      globalThis.__fleetUpdateUiTest = { state, installClicks: 0 }
      const send = () => BrowserWindow.getAllWindows()[0].webContents.send('fleet:update-state', state)
      for (const method of ['checkForUpdates', 'downloadUpdate', 'installUpdate']) ipcMain.removeHandler(`fleet:${method}`)
      ipcMain.handle('fleet:checkForUpdates', () => { Object.assign(state, { phase: 'available', version: nextVersion, message: `发现新版本 v${nextVersion}。` }); send(); return state })
      ipcMain.handle('fleet:downloadUpdate', () => { Object.assign(state, { phase: 'downloading', percent: 42, message: '正在后台下载更新' }); send(); return state })
      ipcMain.handle('fleet:installUpdate', () => { globalThis.__fleetUpdateUiTest.installClicks++; Object.assign(state, { phase: 'installing', message: '正在静默更新，完成后将重新打开舰桥…' }); send() })
      send()
    }, { version, nextVersion, repository })
    await updates.getByRole('button', { name: '检查更新', exact: true }).click()
    await updates.getByRole('button', { name: `下载 v${nextVersion}`, exact: true }).click()
    assert.equal(await updates.getByRole('progressbar', { name: '更新下载进度' }).getAttribute('value'), '42')
    await updates.screenshot({ path: path.join(artifacts, 'updates-downloading.png') })
    await application.evaluate(({ BrowserWindow }) => {
      const state = globalThis.__fleetUpdateUiTest.state
      Object.assign(state, { phase: 'downloaded', percent: 100, message: '更新已下载并校验；退出舰桥时自动静默安装，下次启动使用新版。收起到托盘不会安装。' })
      BrowserWindow.getAllWindows()[0].webContents.send('fleet:update-state', state)
    })
    await updates.getByRole('button', { name: `重启更新 v${nextVersion}`, exact: true }).waitFor()
    await updates.screenshot({ path: path.join(artifacts, 'updates-ready-light.png') })
    await page.locator('.sidebar-bottom').screenshot({ path: path.join(artifacts, 'updates-github-light.png') })
    await page.getByRole('button', { name: '工作台', exact: true }).click()
    await page.locator('.update-banner').getByText(`新版 v${nextVersion} 已下载，退出后自动安装，下次启动生效。`, { exact: true }).waitFor()
    await page.getByRole('button', { name: '收起到托盘', exact: true }).click()
    assert.equal(await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false)
    assert.equal(await application.evaluate(() => globalThis.__fleetUpdateUiTest.installClicks), 0)
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].show())
    await page.getByRole('button', { name: '查看更新', exact: true }).click()
    await page.getByLabel('外观', { exact: true }).selectOption('dark')
    await page.getByRole('button', { name: '保存设置', exact: true }).click()
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark')
    await updates.screenshot({ path: path.join(artifacts, 'updates-ready-dark.png') })
    await page.locator('.sidebar-bottom').screenshot({ path: path.join(artifacts, 'updates-github-dark.png') })
    await updates.getByRole('button', { name: `重启更新 v${nextVersion}`, exact: true }).click()
    await updates.getByText('正在静默更新，完成后将重新打开舰桥…', { exact: true }).waitFor()
    assert.equal(await application.evaluate(() => globalThis.__fleetUpdateUiTest.installClicks), 1)
    assert.equal(fs.existsSync(path.join(sandbox, 'codex', 'config.toml')), false)
    await application.close()
    application = await electron.launch({ args: [root, '--force-device-scale-factor=1'], env })
    const reopened = await application.firstWindow()
    await reopened.getByRole('heading', { name: /你自己的模型舰队/ }).waitFor()
    const saved = await reopened.evaluate(async () => (await window.fleet.snapshot()).settings)
    assert.equal(saved.autoInstallUpdates, true); assert.equal(saved.autoCheckUpdates, true); assert.equal(saved.autoDownloadUpdates, true)
    await reopened.getByRole('button', { name: '设置', exact: true }).click()
    assert.equal(await reopened.getByRole('switch', { name: '自动更新', exact: true }).isChecked(), true)
    await reopened.getByRole('switch', { name: '自动更新', exact: true }).uncheck()
    await reopened.getByRole('button', { name: '保存设置', exact: true }).click()
    await reopened.waitForFunction(async () => (await window.fleet.snapshot()).settings.autoInstallUpdates === false)
    await application.close()
    application = await electron.launch({ args: [root, '--force-device-scale-factor=1'], env })
    const optedOut = await application.firstWindow()
    await optedOut.getByRole('heading', { name: /你自己的模型舰队/ }).waitFor()
    await optedOut.getByRole('button', { name: '设置', exact: true }).click()
    assert.equal(await optedOut.getByRole('switch', { name: '自动更新', exact: true }).isChecked(), false)
    const report = { passed: true, sandbox, checks: ['development mode cannot run installer updates', 'automatic updates default to on and re-enabling also enables check/download', 'disabling automatic download also disables installation', 'enabled and opted-out preferences persist across app restart', 'GitHub icon links use verified IPC to open the real repository', 'check/download/progress/restart UI via real IPC and preload', 'downloaded update banner explains next-launch behavior', 'hiding to tray does not install updates', 'light and dark update controls and GitHub icons', 'no real installer execution or Codex config changes'] }
    fs.writeFileSync(path.join(artifacts, 'updates-ui-report.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report, null, 2))
  } finally { if (application) await application.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
